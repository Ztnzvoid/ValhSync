//! What the admin window says, in every language it says it in.
//!
//! One arm per string rather than one function per language: the translations
//! of a sentence sit on the same rows, where a drifting one is visible, and
//! the match stays exhaustive so a new key cannot be added in one language and
//! forgotten in the rest -- that is a compile error, not a box somebody reads
//! in the wrong tongue three months later.
//!
//! English is the default everywhere. The French and the English are the ones
//! this window was written in; the six that followed were written to be
//! idiomatic rather than literal, and none of them has been read by a native
//! speaker. A correction from one is worth more than an argument from here.
//!
//! The launcher keeps a table of its own, deliberately: the two windows are
//! separate programs with separate vocabularies, and sharing one enum would
//! have every player-facing string compiled into the admin's binary and back.
//! Where both say the same thing -- Settings, Online, to install -- the
//! wording is copied across by hand so the two agree.

/// Languages the admin window speaks, English first because it is the fallback.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Fr,
    De,
    Es,
    It,
    Pl,
    Pt,
    Ru,
}

/// How many there are, and therefore how wide every row below is.
pub const LANGS: usize = 8;

impl Lang {
    /// In the order they are offered, which is the order of the rows.
    pub const ALL: [Self; LANGS] = [
        Self::En,
        Self::Fr,
        Self::De,
        Self::Es,
        Self::It,
        Self::Pl,
        Self::Pt,
        Self::Ru,
    ];

    /// English unless something else was chosen and is understood.
    ///
    /// Matched on the prefix, so `fr-FR`, `pt-BR` and `de_DE` all land where
    /// they should -- and so do the `FR` and `EN` older configurations were
    /// written with. Anything unknown falls back rather than guessing.
    #[must_use]
    pub fn detect(setting: Option<&str>) -> Self {
        let Some(code) = setting.map(str::to_lowercase) else {
            return Self::En;
        };
        for lang in Self::ALL {
            if code.starts_with(lang.code()) {
                return lang;
            }
        }
        Self::En
    }

    /// The tag stored in the configuration.
    #[must_use]
    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Fr => "fr",
            Self::De => "de",
            Self::Es => "es",
            Self::It => "it",
            Self::Pl => "pl",
            Self::Pt => "pt",
            Self::Ru => "ru",
        }
    }

    /// The name of the language in itself. A menu offering "German" to
    /// somebody who only reads German has offered them nothing.
    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Fr => "Français",
            Self::De => "Deutsch",
            Self::Es => "Español",
            Self::It => "Italiano",
            Self::Pl => "Polski",
            Self::Pt => "Português",
            Self::Ru => "Русский",
        }
    }
}

